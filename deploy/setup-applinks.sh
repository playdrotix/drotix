#!/usr/bin/env bash
# DROTIX: enable Android App Links (/.well-known/assetlinks.json) and invite links (/join/<CODE>) on Nginx.
# Run on the VPS:  sudo bash /var/www/playdrotix/drotix/deploy/setup-applinks.sh
set -euo pipefail

SITE_ROOT="${SITE_ROOT:-/var/www/playdrotix/drotix}"
SNIPPET=/etc/nginx/snippets/drotix-applinks.conf

# PHP-FPM socket (php8.3 on this server; auto-detect otherwise)
SOCK=$(ls /run/php/php*-fpm.sock 2>/dev/null | sort -V | tail -1 || true)
[ -z "$SOCK" ] && SOCK=/run/php/php-fpm.sock
echo "PHP socket : $SOCK"

[ -f "$SITE_ROOT/.well-known/assetlinks.json" ] || { echo "ERROR: $SITE_ROOT/.well-known/assetlinks.json missing (git pull?)"; exit 1; }
[ -f "$SITE_ROOT/join/index.php" ]              || { echo "ERROR: $SITE_ROOT/join/index.php missing (git pull?)"; exit 1; }

# 1. Snippet with the rules (exact-match locations beat any "deny dotfiles" regex)
mkdir -p /etc/nginx/snippets
cat > "$SNIPPET" <<EOF
# DROTIX App Links + invite page (generated by deploy/setup-applinks.sh)
location = /.well-known/assetlinks.json {
    root $SITE_ROOT;
    default_type application/json;
    add_header Cache-Control "public, max-age=300" always;
    add_header Access-Control-Allow-Origin "*" always;
    try_files \$uri =404;
}
location = /.well-known/apple-app-site-association {
    root $SITE_ROOT;
    default_type application/json;
    add_header Cache-Control "public, max-age=300" always;
    try_files \$uri =404;
}
location ~ ^/join(/.*)?\$ {
    include fastcgi_params;
    fastcgi_param SCRIPT_FILENAME $SITE_ROOT/join/index.php;
    fastcgi_param SCRIPT_NAME /join/index.php;
    fastcgi_param REQUEST_URI \$request_uri;
    fastcgi_pass unix:$SOCK;
}
EOF
echo "Snippet    : $SNIPPET"

# 2. Find the nginx file(s) whose server block serves playdrotix.in
FILES=$(nginx -T 2>/dev/null | awk '
  /^# configuration file /{f=$4; sub(/:$/,"",f)}
  /server_name/ && /playdrotix\.in/ {print f}
  /^[ \t]*root[ \t]+\/var\/www\/playdrotix/ {print f}' | sort -u)

if [ -z "$FILES" ]; then
  echo "ERROR: could not find the server block for playdrotix.in. Send this output to the developer:"
  nginx -T 2>/dev/null | grep -nE "configuration file|server_name|listen|root|proxy_pass" | head -80
  exit 1
fi

# 3. Add 'include snippets/drotix-applinks.conf;' right after each server_name line for playdrotix
for F in $FILES; do
  echo "Config     : $F"
  if grep -q "drotix-applinks.conf" "$F"; then
    echo "             (already included)"; continue
  fi
  cp -a "$F" "$F.bak.$(date +%Y%m%d%H%M%S)"
  sed -i -E '/^[[:space:]]*server_name[^;]*playdrotix\.in[^;]*;/a\    include snippets/drotix-applinks.conf;' "$F"
  grep -q "drotix-applinks.conf" "$F" || echo "WARNING: no server_name playdrotix.in line in $F, add 'include snippets/drotix-applinks.conf;' inside its server { } by hand"
done

# 4. Test and reload (restore backups if the test fails)
if nginx -t; then
  systemctl daemon-reload || true
  systemctl reload nginx
  echo "Nginx reloaded."
else
  echo "nginx -t FAILED, restoring backups"
  for F in $FILES; do B=$(ls -t "$F".bak.* 2>/dev/null | head -1); [ -n "$B" ] && cp -a "$B" "$F"; done
  nginx -t && systemctl reload nginx
  exit 1
fi

# 5. Checks
echo; echo "== assetlinks.json =="; curl -sI https://playdrotix.in/.well-known/assetlinks.json | grep -iE "^HTTP|content-type|location" || true
echo "== /join/K7P2QX ==";       curl -sI https://playdrotix.in/join/K7P2QX | grep -iE "^HTTP|location" || true
echo "== og:description ==";     curl -s  https://playdrotix.in/join/K7P2QX | grep -o 'og:description" content="[^"]*' || true
